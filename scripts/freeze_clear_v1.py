from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from longrun.benchmarks.clear_v1 import (
    build_split_manifest,
    generate_clear_v1_tasks,
    run_scripted_baselines,
    task_record,
)


def _write_json(path: Path, payload: dict) -> str:
    text = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("benchmarks/clear-300-v1"),
    )
    parser.add_argument("--seed", type=int, default=20261028)
    args = parser.parse_args()

    tasks = generate_clear_v1_tasks(seed=args.seed)
    records = [
        {
            **task_record(task),
            "task_sha256": hashlib.sha256(
                json.dumps(
                    task_record(task),
                    sort_keys=True,
                    separators=(",", ":"),
                    ensure_ascii=True,
                ).encode("utf-8")
            ).hexdigest(),
        }
        for task in sorted(tasks, key=lambda task: task.task_id)
    ]
    manifest = build_split_manifest(tasks, seed=args.seed)
    baselines = run_scripted_baselines(tasks)
    tasks_hash = _write_json(
        args.output_dir / "tasks.json",
        {
            "schema": 1,
            "name": "clear-300-v1",
            "seed": args.seed,
            "tasks": records,
        },
    )
    manifest_hash = _write_json(
        args.output_dir / "split-manifest.json",
        manifest,
    )
    baseline_hash = _write_json(
        args.output_dir / "scripted-baselines.json",
        baselines,
    )
    readme = (
        "# CLEAR-300-v1\n\n"
        "Frozen CPU-first benchmark generated by\n"
        "`python3 scripts/freeze_clear_v1.py`.\n\n"
        f"- Seed: `{args.seed}`\n"
        f"- Tasks: `{len(records)}`\n"
        "- Splits: `train=180`, `dev=60`, `test=60`\n"
        "- Environments: 100 filesystem, 100 mock browser, 100 gridworld\n"
        f"- Canonical task-list SHA-256: `{manifest['canonical_sha256']}`\n"
        f"- `tasks.json` SHA-256: `{tasks_hash}`\n"
        f"- `split-manifest.json` SHA-256: `{manifest_hash}`\n"
        f"- `scripted-baselines.json` SHA-256: `{baseline_hash}`\n\n"
        "The split is by rule variant: variants 0-2 are train, 3 is dev,\n"
        "and 4 is test. Do not edit frozen files in place; create v2.\n\n"
        "The browser and gridworld environments are deterministic local\n"
        "mocks, not external browser or game engines.\n"
    )
    readme_path = args.output_dir / "README.md"
    readme_path.write_text(readme, encoding="utf-8")
    print(
        json.dumps(
            {
                "tasks": len(records),
                "canonical_sha256": manifest["canonical_sha256"],
                "tasks_sha256": tasks_hash,
                "manifest_sha256": manifest_hash,
                "baselines_sha256": baseline_hash,
            },
            indent=2,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
